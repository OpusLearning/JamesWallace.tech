// Pre-build: a copy of Bootstrap's CSS holding only the rules this site can use (site audit 18 Oct 2026, G1).
//
// The stylesheet is render-blocking, and 232 KB of its 293 KB was Bootstrap, nearly all unused. Only
// Bootstrap is trimmed: the site's own index.css is left whole. Kept selectors are those whose classes,
// ids or elements appear as words in src/ or index.html, which holds every className string, including
// the ones toggled at runtime. A class built from a variable must be a whole word in the source.
// Writes src/styles/bootstrap.purged.css (gitignored), imported by main.jsx and App.jsx.
import { PurgeCSS } from 'purgecss';
import { writeFile, mkdir } from 'node:fs/promises';

const ROOT = new URL('../', import.meta.url).pathname;
const OUT = `${ROOT}src/styles/bootstrap.purged.css`;

const [result] = await new PurgeCSS().purge({
  content: [`${ROOT}index.html`, `${ROOT}src/**/*.{js,jsx}`],
  css: [`${ROOT}node_modules/bootstrap/dist/css/bootstrap.min.css`],
  // Rules on these attributes are matched by value, not by a word in the source.
  dynamicAttributes: ['type', 'role', 'disabled', 'readonly', 'hidden'],
});
await mkdir(`${ROOT}src/styles`, { recursive: true });
await writeFile(OUT, `/* Generated by scripts/purge-bootstrap.mjs from bootstrap.min.css. Do not edit. */\n${result.css}`);
console.log(`bootstrap.purged.css: ${Math.round(result.css.length / 1024)} KB (from 227 KB)`);
